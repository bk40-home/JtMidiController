// One row per readable older table.  Looked up by the file header's
// paramCount; a row whose count equals the running table is skipped by
// PatchStore (that file loads on the direct path).
struct LegacyTable {
    uint16_t        count;   // header paramCount this list decodes
    const uint16_t* ids;     // ParamID at each OLD ordinal, count entries
};

static const LegacyTable kLegacyTables[] = {
    { 250,             kLegacyIds250 },
    { kLegacyCount252, kLegacyIds252 },
    { 303,             kLegacyIds303 },
    { 304,             kLegacyIds304 },
    { 305,             kLegacyIds305 },
};

static constexpr size_t kLegacyTableCount = sizeof(kLegacyTables) / sizeof(kLegacyTables[0]);

// nullptr if no frozen list decodes a file of this count.  Linear: 5 rows,
// run once per patch load, never on the audio or UI hot path.
inline const LegacyTable* findLegacyTable(uint16_t paramCount) {
    for (size_t i = 0; i < kLegacyTableCount; ++i)
        if (kLegacyTables[i].count == paramCount) return &kLegacyTables[i];
    return nullptr;
}

